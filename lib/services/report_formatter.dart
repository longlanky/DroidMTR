import 'dart:convert';

import 'package:intl/intl.dart';
import 'package:share_plus/share_plus.dart';

import '../models/trace_models.dart';

class ReportFormatter {
  static final DateFormat _dateFormat = DateFormat('yyyy-MM-dd HH:mm:ss');

  static String text(TraceSession session) {
    final buffer = StringBuffer();
    buffer.writeln('DroidMTR trace report');
    buffer.writeln('Target: ${session.host} (${session.address})');
    buffer.writeln(
      'Started: ${_dateFormat.format(session.startedAt.toLocal())}',
    );
    buffer.writeln('Duration: ${formatDuration(session.durationMs)}');
    buffer.writeln(
      'Probe: ${session.mode.label}  |  Max hops: ${session.config.maxHops}  |  '
      'Interval: ${session.config.intervalLabel}  |  Timeout: ${session.config.timeoutLabel}',
    );
    buffer.writeln(
      session.reached
          ? 'Result: destination reached at hop ${session.reachedTtl}'
          : 'Result: destination not reached within ${session.config.maxHops} hops',
    );
    buffer.writeln();
    buffer.writeln(
      '| # | Host | Loss% | Sent | Recv | Best | Avrg | Worst | Last |',
    );
    buffer.writeln(
      '|---|------|-------|------|------|------|------|-------|------|',
    );
    for (final hop in session.hops) {
      if (!hop.hasData) continue;
      final host = hop.address ?? '*';
      buffer.writeln(
        '| ${hop.ttl} | $host | ${formatLoss(hop.lossPercent)} | '
        '${hop.sent} | ${hop.received} | ${_ms(hop.bestUs)} | '
        '${_ms(hop.avgUs)} | ${_ms(hop.worstUs)} | ${_ms(hop.lastUs)} |',
      );
    }
    buffer.writeln();
    buffer.writeln('Generated by DroidMTR');
    return buffer.toString();
  }

  static String csv(TraceSession session) {
    final buffer = StringBuffer();
    buffer.writeln(
      'ttl,hostname,address,loss_percent,sent,recv,best_ms,avg_ms,worst_ms,stdev_ms,last_ms,jitter_ms,alternates',
    );
    for (final hop in session.hops) {
      if (!hop.hasData) continue;
      buffer.writeln(
        [
          hop.ttl.toString(),
          _csv(hop.hostname ?? ''),
          _csv(hop.address ?? ''),
          hop.lossPercent.toStringAsFixed(2),
          hop.sent.toString(),
          hop.received.toString(),
          _number(hop.bestMs),
          _number(hop.avgMs),
          _number(hop.worstMs),
          _number(hop.stdevMs),
          _number(hop.lastMs),
          _number(hop.jitterMs),
          _csv(hop.alternates.join(' ')),
        ].join(','),
      );
    }
    return buffer.toString();
  }

  static String _ms(int microseconds) {
    if (microseconds <= 0) return '—';
    return (microseconds / 1000.0).toStringAsFixed(1);
  }

  static String _number(double value) =>
      value <= 0 ? '' : value.toStringAsFixed(2);

  static String _csv(String value) {
    if (value.contains(',') || value.contains('"') || value.contains('\n')) {
      return '"${value.replaceAll('"', '""')}"';
    }
    return value;
  }
}

class ReportSharer {
  static Future<void> shareText(TraceSession session) async {
    await SharePlus.instance.share(
      ShareParams(
        text: ReportFormatter.text(session),
        subject: 'DroidMTR trace — ${session.host}',
        title: 'Share trace report',
      ),
    );
  }

  static Future<void> shareCsv(TraceSession session) async {
    final safeHost = session.host.replaceAll(RegExp(r'[^A-Za-z0-9._-]'), '_');
    final name =
        'droidmtr_${safeHost}_${session.startedAt.millisecondsSinceEpoch}.csv';
    await SharePlus.instance.share(
      ShareParams(
        files: [
          XFile.fromData(
            utf8.encode(ReportFormatter.csv(session)),
            mimeType: 'text/csv',
            name: name,
          ),
        ],
        fileNameOverrides: [name],
        subject: 'DroidMTR trace — ${session.host}',
        title: 'Share trace data',
      ),
    );
  }
}
